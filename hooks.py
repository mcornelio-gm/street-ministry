"""MkDocs build hooks.

on_pre_build regenerates these wiki index pages so they always match the site:
  - Documents/Routes/index.md        <- data/routes.json
  - Documents/Stories/index.md       <- Documents/Stories/*.md (front matter)
  - Documents/Announcements/index.md <- Documents/Announcements/*.md (front matter)
  - Documents/Guides/index.md        <- Documents/Guides/*.md (front matter)
  - Documents/Teams/index.md         <- Documents/Teams/*.md (front matter)
  - Documents/About/index.md         <- Documents/About/*.md (front matter)
Do not edit those index.md files by hand.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from app import md_engine  # noqa: E402

ROUTES_JSON = os.path.join(ROOT, "data", "routes.json")
ROUTES_MD = os.path.join(ROOT, "Documents", "Routes", "index.md")
STORIES_MD = os.path.join(ROOT, "Documents", "Stories", "index.md")
ANNOUNCEMENTS_MD = os.path.join(ROOT, "Documents", "Announcements", "index.md")
GUIDES_MD = os.path.join(ROOT, "Documents", "Guides", "index.md")
TEAMS_MD = os.path.join(ROOT, "Documents", "Teams", "index.md")
ABOUT_MD = os.path.join(ROOT, "Documents", "About", "index.md")
CITY_ORDER = ["Fremont", "Newark", "Union City", "Hayward"]
GENERATED_NOTE = "<!-- AUTO-GENERATED by hooks.py at build time. Do not edit by hand. -->"


def _cell(text) -> str:
    """Make a value safe for a markdown table cell."""
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def render_routes_md(routes: list) -> str:
    from app.routes_data import route_cities
    cities = sorted(
        {c for r in routes for c in route_cities(r)},
        key=lambda c: (CITY_ORDER.index(c) if c in CITY_ORDER else len(CITY_ORDER), c),
    )
    lines = [
        "---",
        "title: Street Outreach Routes",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Street Outreach Routes",
        "",
        f"{len(routes)} active routes across {', '.join(cities)}. "
        "For the interactive map, visit the [Routes tab](/routes).",
        "",
    ]
    for r in sorted(routes, key=lambda x: x["name"].lower()):
        lines += [f"## {r['name']}", ""]
        facts = []
        if r.get("leaders"):
            facts.append(f"**Leaders:** {r['leaders']}")
        if r.get("schedule"):
            facts.append(f"**Schedule:** {r['schedule']}")
        if route_cities(r):
            facts.append(f"**Cities:** {', '.join(route_cities(r))}")
        if facts:
            lines += ["  \n".join(facts), ""]
        if r.get("summary"):
            lines += [r["summary"], ""]
        lines += ["| # | Stop | Address |", "|:--|:-----|:--------|"]
        for i, s in enumerate(r["stops"], 1):
            addr = _cell(s.get("address"))
            if s.get("lat") is not None and s.get("lng") is not None:
                addr += f" ([map](https://www.google.com/maps/search/?api=1&query={s['lat']},{s['lng']}))"
            lines.append(f"| {i} | **{_cell(s.get('name'))}** | {addr} |")
        lines.append("")
        if r.get("notes"):
            lines += [f"> {line}" if line else ">" for line in r["notes"].splitlines()] + [""]
    return "\n".join(lines)


def render_stories_md(stories: list) -> str:
    lines = [
        "---",
        "title: Stories from the Street",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Stories from the Street",
        "",
        "Real encounters, answered prayers, and moments of mutual transformation from the "
        "sidewalks, motels, and encampments across Fremont, Newark, Union City, and Hayward.",
        "",
    ]
    for s in stories:
        lines.append(f"* [{s['title']} ({s['city']})]({s['filename']}) — {s['date_display']}")
    lines.append("")
    return "\n".join(lines)


def render_announcements_md(announcements: list) -> str:
    lines = [
        "---",
        "title: Street Ministry Announcements Archive",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Ministry Announcements",
        "",
        "Official announcements, supply drives, and operational schedule updates for the "
        "Resonate Church Street Ministry team.",
        "",
    ]
    for a in announcements:
        lines.append(f"* [{a['title']}]({a['filename']}) — {a['date_display']}")
    lines.append("")
    return "\n".join(lines)


def render_section_md(title: str, intro: str, docs: list) -> str:
    lines = [
        "---",
        f"title: {title}",
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"# {title}",
        "",
        intro,
        "",
    ]
    for d in docs:
        line = f"* [{d['title']}]({d['filename']})"
        if d.get("summary"):
            line += f" — {d['summary']}"
        lines.append(line)
    lines.append("")
    return "\n".join(lines)


def render_guides_md(guides: list) -> str:
    return render_section_md(
        "Guides",
        "Orientation, safety, and how-to guides for Street Ministry outreach teams.",
        guides,
    )


def render_teams_md(teams: list) -> str:
    return render_section_md(
        "Teams",
        "Get involved and serve with our Resonate Church Street Ministry outreach teams.",
        teams,
    )


def render_about_md(about_docs: list) -> str:
    return render_section_md(
        "About",
        "Who we are, street realities in Alameda County, critical needs, and how to reach us.",
        about_docs,
    )


def _write_if_changed(path: str, content: str):
    """Only write when changed, so `mkdocs serve` doesn't loop on its own output."""
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if content != existing:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)


def on_pre_build(config, **kwargs):
    from app import routes_data
    routes = routes_data.get_all_routes()  # normalized (adds city, defaults)
    _write_if_changed(ROUTES_MD, render_routes_md(routes))
    _write_if_changed(STORIES_MD, render_stories_md(md_engine.get_stories()))
    _write_if_changed(ANNOUNCEMENTS_MD, render_announcements_md(md_engine.get_announcements()))
    _write_if_changed(GUIDES_MD, render_guides_md(md_engine.get_guides()))
    _write_if_changed(TEAMS_MD, render_teams_md(md_engine.get_teams()))
    _write_if_changed(ABOUT_MD, render_about_md(md_engine.get_about_docs()))

