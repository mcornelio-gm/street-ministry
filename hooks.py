"""MkDocs build hooks.

on_pre_build regenerates these wiki index pages so they always match the site:
  - Documents/Routes/index.md        <- data/routes.json
  - Documents/Stories/index.md       <- Documents/Stories/*.md (front matter)
  - Documents/Announcements/index.md <- Documents/Announcements/*.md (front matter)
Do not edit those index.md files by hand.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from app import md_engine  # noqa: E402

ROUTES_JSON = os.path.join(ROOT, "data", "routes.json")
ROUTES_MD = os.path.join(ROOT, "Documents", "Routes", "index.md")
STORIES_MD = os.path.join(ROOT, "Documents", "Stories", "index.md")
ANNOUNCEMENTS_MD = os.path.join(ROOT, "Documents", "Announcements", "index.md")
CITY_ORDER = ["Fremont", "Newark", "Union City", "Hayward"]
GENERATED_NOTE = "<!-- AUTO-GENERATED by hooks.py at build time. Do not edit by hand. -->"


def _cell(text) -> str:
    """Make a value safe for a markdown table cell."""
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def render_routes_md(routes: list) -> str:
    cities = sorted(
        {r.get("city", "Other") for r in routes},
        key=lambda c: (CITY_ORDER.index(c) if c in CITY_ORDER else len(CITY_ORDER), c),
    )
    lines = [
        "---",
        "title: Street Outreach Routes",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Street Outreach Routes",
        "",
        f"{len(routes)} active routes across {', '.join(cities)}. "
        "For the interactive map, visit the [Routes tab](/routes).",
        "",
    ]
    for city in cities:
        lines += [
            f"## {city}",
            "",
            "| Route | Location | Schedule | Team Lead | Description |",
            "|:------|:---------|:---------|:----------|:------------|",
        ]
        for r in (x for x in routes if x.get("city", "Other") == city):
            loc = _cell(r.get("target"))
            if r.get("lat") is not None and r.get("lng") is not None:
                loc += (
                    f" ([map](https://www.google.com/maps/search/?api=1&query={r['lat']},{r['lng']}))"
                )
            lines.append(
                f"| **{_cell(r.get('name'))}** | {loc} | {_cell(r.get('schedule'))} "
                f"| {_cell(r.get('lead'))} | {_cell(r.get('description'))} |"
            )
        lines.append("")
    return "\n".join(lines)


def render_stories_md(stories: list) -> str:
    lines = [
        "---",
        "title: Stories from the Street",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Stories from the Street",
        "",
        "Real encounters, answered prayers, and moments of mutual transformation from the "
        "sidewalks, motels, and encampments across Fremont, Newark, Union City, and Hayward.",
        "",
    ]
    for s in stories:
        lines.append(f"* [{s['title']} ({s['city']})]({s['filename']}) — {s['date_display']}")
    lines.append("")
    return "\n".join(lines)


def render_announcements_md(announcements: list) -> str:
    lines = [
        "---",
        "title: Street Ministry Announcements Archive",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Ministry Announcements",
        "",
        "Official announcements, supply drives, and operational schedule updates for the "
        "Resonate Church Street Ministry team.",
        "",
    ]
    for a in announcements:
        lines.append(f"* [{a['title']}]({a['filename']}) — {a['date_display']}")
    lines.append("")
    return "\n".join(lines)


def _write_if_changed(path: str, content: str):
    """Only write when changed, so `mkdocs serve` doesn't loop on its own output."""
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if content != existing:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)


def on_pre_build(config, **kwargs):
    with open(ROUTES_JSON, encoding="utf-8") as f:
        routes = json.load(f)
    _write_if_changed(ROUTES_MD, render_routes_md(routes))
    _write_if_changed(STORIES_MD, render_stories_md(md_engine.get_stories()))
    _write_if_changed(ANNOUNCEMENTS_MD, render_announcements_md(md_engine.get_announcements()))

